export type SpotPageV6Copy = (typeof spotPageV6)['pt'];

/** Copy da página v6 para um locale (es/de/fr → EN). */
export function spotV6Copy(locale: string): SpotPageV6Copy {
  return locale === 'pt' ? spotPageV6.pt : spotPageV6.en;
}

/** Substitui `{chave}` pelos valores. */
export function fmtCopy(s: string, v: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m));
}
